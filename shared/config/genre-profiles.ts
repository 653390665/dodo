/**
 * Look up a genre profile by id.
 * Returns undefined if not found.
 */
export function getGenreProfile(id: string): GenreProfile | undefined {
  return GENRE_PROFILES.find((g) => g.id === id);
}

/**
 * Get genre prompt augmentation for injection into AI prompts.
 * Returns empty string if genre not found or has no augmentation.
 */
export function getGenrePromptAugmentation(id: string): string {
  const profile = getGenreProfile(id);
  return profile?.promptAugmentation ?? '';
}
